/**
 * Builds src/lib/map-paths.ts from Natural Earth admin-1 data (public domain).
 *   npm run map:build
 * Projection: equirectangular scaled by cos(latitude centre); Douglas–Peucker
 * simplification keeps the file small (a few KB).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { regions } from '../src/lib/regions'

type Ring = Array<[number, number]>
type Feature = { properties: { iso: string; name: string }; geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: unknown } }

const geo = JSON.parse(readFileSync('scripts/mrt-admin1.naturalearth.geojson', 'utf8')) as { features: Array<Feature> }
const LAT0 = 20.5
const K = Math.cos((LAT0 * Math.PI) / 180)
const WIDTH = 1000

function rings(f: Feature): Array<Ring> {
  if (f.geometry.type === 'Polygon') return (f.geometry.coordinates as Array<Ring>).slice(0, 1)
  return (f.geometry.coordinates as Array<Array<Ring>>).map((p) => p[0])
}

const all = geo.features.flatMap(rings).flat()
const xs = all.map(([lon]) => lon * K)
const ys = all.map(([, lat]) => -lat)
const minX = Math.min(...xs)
const maxX = Math.max(...xs)
const minY = Math.min(...ys)
const maxY = Math.max(...ys)
const scale = WIDTH / (maxX - minX)
const HEIGHT = Math.round((maxY - minY) * scale)

function project([lon, lat]: [number, number]): [number, number] {
  return [(lon * K - minX) * scale, (-lat - minY) * scale]
}

function perpDist(p: [number, number], a: [number, number], b: [number, number]) {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / Math.hypot(dx, dy)
}

function simplify(pts: Array<[number, number]>, eps: number): Array<[number, number]> {
  if (pts.length < 3) return pts
  let idx = 0
  let max = 0
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perpDist(pts[i], pts[0], pts.at(-1)!)
    if (d > max) {
      max = d
      idx = i
    }
  }
  if (max > eps) return [...simplify(pts.slice(0, idx + 1), eps).slice(0, -1), ...simplify(pts.slice(idx), eps)]
  return [pts[0], pts.at(-1)!]
}

const out: Record<string, { d: string; cx: number; cy: number }> = {}
for (const f of geo.features) {
  const region = regions.find((r) => r.iso === f.properties.iso)
  if (!region) throw new Error(`no region for ${f.properties.iso} ${f.properties.name}`)
  const parts = rings(f).map((ring) => simplify(ring.map(project), 1.2))
  const d = parts
    .filter((p) => p.length > 2)
    .map((p) => `M${p.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`)
    .join('')
  // Label anchor: area centroid (shoelace) of the largest ring.
  const area = (r: Array<[number, number]>) => r.reduce((s, p, i) => s + p[0] * r[(i + 1) % r.length][1] - r[(i + 1) % r.length][0] * p[1], 0) / 2
  const biggest = [...parts].sort((a, b) => Math.abs(area(b)) - Math.abs(area(a)))[0]
  const A = area(biggest)
  let cx = 0
  let cy = 0
  biggest.forEach((p, i) => {
    const q = biggest[(i + 1) % biggest.length]
    const cross = p[0] * q[1] - q[0] * p[1]
    cx += (p[0] + q[0]) * cross
    cy += (p[1] + q[1]) * cross
  })
  cx /= 6 * A
  cy /= 6 * A
  out[region.slug] = { d, cx: Math.round(cx), cy: Math.round(cy) }
}

const file = `// Generated by scripts/build-map.ts from Natural Earth admin-1 (public domain). Do not edit.
export const MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'
export const MAP_PATHS: Record<string, { d: string; cx: number; cy: number }> = ${JSON.stringify(out)}
`
writeFileSync('src/lib/map-paths.ts', file)
console.info(`map: ${Object.keys(out).length} regions, ${(file.length / 1024).toFixed(1)} KB, viewBox ${WIDTH}x${HEIGHT}`)
